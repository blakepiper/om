#!/usr/bin/env python3
"""Optional asset regeneration; Pango/Cairo are not build/runtime dependencies.

Use an installed FreeSans font with Devanagari shaping. The generated header
contains only the rasterized mantra, so om itself never loads a font library.
"""
import ctypes as C
import ctypes.util
from pathlib import Path
import sys


def library(name, package):
    path = ctypes.util.find_library(name)
    paths = ([path] if path else []) + sorted(Path('/nix/store').glob(f'*-{package}-*/lib/lib{name}.so'))
    for candidate in paths:
        try:
            return C.CDLL(str(candidate))
        except OSError:
            pass  # A Nix store can contain libraries for several architectures.
    raise SystemExit(f'Optional asset generator requires {name}.')


cairo = library('cairo', 'cairo')
pango = library('pango-1.0', 'pango')
pc = library('pangocairo-1.0', 'pango')


def bind(lib, name, restype, *args):
    fn = getattr(lib, name)
    fn.restype, fn.argtypes = restype, args
    return fn


ptr, integer, real = C.c_void_p, C.c_int, C.c_double
surface = bind(cairo, 'cairo_image_surface_create', ptr, integer, integer, integer)
context = bind(cairo, 'cairo_create', ptr, ptr)
rgb = bind(cairo, 'cairo_set_source_rgb', None, ptr, real, real, real)
paint = bind(cairo, 'cairo_paint', None, ptr)
move = bind(cairo, 'cairo_move_to', None, ptr, real, real)
layout = bind(pc, 'pango_cairo_create_layout', ptr, ptr)
font = bind(pango, 'pango_font_description_from_string', ptr, C.c_char_p)
set_font = bind(pango, 'pango_layout_set_font_description', None, ptr, ptr)
set_text = bind(pango, 'pango_layout_set_text', None, ptr, C.c_char_p, integer)
set_width = bind(pango, 'pango_layout_set_width', None, ptr, integer)
set_align = bind(pango, 'pango_layout_set_alignment', None, ptr, integer)
show = bind(pc, 'pango_cairo_show_layout', None, ptr, ptr)
flush = bind(cairo, 'cairo_surface_flush', None, ptr)
data = bind(cairo, 'cairo_image_surface_get_data', ptr, ptr)
stride = bind(cairo, 'cairo_image_surface_get_stride', integer, ptr)
png = bind(cairo, 'cairo_surface_write_to_png', integer, ptr, C.c_char_p)


class Rectangle(C.Structure):
    _fields_ = [(field, integer) for field in ('x', 'y', 'width', 'height')]


extents = bind(pango, 'pango_layout_get_pixel_extents', None, ptr,
               C.POINTER(Rectangle), C.POINTER(Rectangle))
def main():
    root = Path(__file__).resolve().parents[1]
    output = ['/* Generated by scripts/generate-mantra.py with Pango + FreeSans Bold.',
              '   Properly shaped Devanagari, rasterized once; no font dependency in om. */',
              'typedef struct { int width, height; const unsigned char *bits; } MantraMask;']
    assets = [('line', 'ॐ मणि पद्मे हूँ'), ('stack', 'ॐ मणि\nपद्मे हूँ')]
    assets += [(f'word_{i}', text) for i, text in enumerate(('ॐ', 'मणि', 'पद्मे', 'हूँ'))]
    assets += [(f'latin_{i}', text) for i, text in enumerate(('om', 'mani', 'padme', 'hum'))]
    for name, text in assets:
        probe = context(surface(0, 1, 1))
        shaped = layout(probe)
        set_font(shaped, font(b'FreeSans Bold 48'))
        set_text(shaped, text.encode(), -1)
        ink, logical = Rectangle(), Rectangle()
        extents(shaped, C.byref(ink), C.byref(logical))
        set_width(shaped, logical.width * 1024)
        set_align(shaped, 1)
        extents(shaped, C.byref(ink), C.byref(logical))
        width, height = ink.width+4, ink.height+4
        image = surface(0, width, height)
        cr = context(image)
        rgb(cr, 0, 0, 0)
        paint(cr)
        rgb(cr, 1, 1, 1)
        move(cr, 2-ink.x, 2-ink.y)
        show(cr, shaped)
        flush(image)
        raw = C.string_at(data(image), stride(image)*height)
        bits = bytearray((width*height+7)//8)
        red = 2 if sys.byteorder == 'little' else 1
        for y in range(height):
            for x in range(width):
                if raw[y*stride(image)+x*4+red] >= 100:
                    index = y*width+x
                    bits[index//8] |= 1 << (index%8)
        output.append(f'static const unsigned char mantra_{name}_bits[] = {{')
        for offset in range(0, len(bits), 20):
            output.append('    '+','.join(f'0x{value:02x}' for value in bits[offset:offset+20])+',')
        output += ['};', f'static const MantraMask mantra_{name} = '
                   f'{{{width},{height},mantra_{name}_bits}};']
        preview = root/'.cache'/f'mantra-{name}.png'
        preview.parent.mkdir(exist_ok=True)
        if png(image, str(preview).encode()):
            raise SystemExit('Failed to write preview')
        print(f'{name}: {width} x {height}, {len(bits)} bytes, {preview}')
    (root/'src/mantra.h').write_text('\n'.join(output)+'\n')


if __name__ == "__main__":
    main()
